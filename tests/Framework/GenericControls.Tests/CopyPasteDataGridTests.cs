    [TestMethod]
    public void Copy_PutsTheSelectedBlockOnTheClipboard_AsTabSeparatedRows_WithOrWithoutHeaders()
    {
        HeadlessSession.Run(() =>
        {
            var (window, grid) = ShowGrid(Rows());
            SelectBlock(grid, 1, 0, 2, 1);

            grid.CopySelectedCellsToClipboard(false);
            Assert.AreEqual($"Item 2\t{21.0}\nItem 3\t{31.5}", Clipboard.GetText());

            grid.CopySelectedCellsToClipboard(true);
