    // Right-clicks the middle of a control, as a user would.
    private static void RightClick(Window window, Control control)
    {
        Avalonia.Point point = control.TranslatePoint(new Avalonia.Point(control.Bounds.Width / 2, control.Bounds.Height / 2), window)!.Value;
        window.MouseDown(point, MouseButton.Right);
        window.MouseUp(point, MouseButton.Right);
        Settle();
    }
