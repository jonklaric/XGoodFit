            grid.AddRows(2);
            Assert.AreEqual(4, table.Rows.Count);

            Select(grid, (0, 0));
            Clipboard.SetText("10\t20\n30\t40");
            grid.PasteClipboard();
            CollectionAssert.AreEqual(new object[] { 10.0, 20.0 }, table.Rows[0].ItemArray);
            CollectionAssert.AreEqual(new object[] { 30.0, 40.0 }, table.Rows[1].ItemArray);
            window.Close();
        });
    }

    [TestMethod]
    public void Rows_OfASortedGrid_AreInsertedAndDeletedWhereTheyShow()
    {
        HeadlessSession.Run(() =>
        {
            var rows = Rows(3);
            var (window, grid) = ShowGrid(rows);
            grid.Items.SortDescriptions.Add(DataGridSortDescription.FromPath(nameof(GridRow.Value), System.ComponentModel.ListSortDirection.Descending));
            Settle();
            Assert.AreEqual("Item 3", ((GridRow)grid.Items[0]).Name);

            // Deleting the first row shown deletes Item 3, the last in the list.
            Select(grid, (0, 0));
            grid.DeleteRows();
            CollectionAssert.AreEqual(new[] { "Item 1", "Item 2" }, rows.Select(r => r.Name).ToArray());

            // Inserting above the first row shown (Item 2) inserts before Item 2 in the list.
            Select(grid, (0, 0));
            grid.InsertRows();
            CollectionAssert.AreEqual(new[] { "Item 1", "", "Item 2" }, rows.Select(r => r.Name).ToArray());

            grid.ClearSort();
            Assert.AreEqual(0, grid.Items.SortDescriptions.Count);
            window.Close();
        });
    }

