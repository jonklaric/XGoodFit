    [TestMethod]
    public void AddInsertAndDeleteRows_ChangeTheItems_AndRaiseTheirEvents()
    {
        HeadlessSession.Run(() =>
        {
            var rows = Rows(3);
            var (window, grid) = ShowGrid(rows);
            var events = new List<string>();
            grid.PreviewAddRows += (int start, int count, ref bool cancel) => events.Add($"preview add {start} {count}");
            grid.RowsAdded += (start, count) => events.Add($"added {start} {count}");
            grid.PreviewDeleteRows += (List<int> indices, ref bool cancel) => events.Add("preview delete " + string.Join(",", indices.OrderBy(i => i)));
            grid.RowsDeleted += indices => events.Add("deleted " + string.Join(",", indices));

            grid.AddRows(2);
            Assert.AreEqual(5, rows.Count);
            Assert.AreEqual(5, grid.Items.Count);

            SelectBlock(grid, 1, 0, 2, 1);
            grid.InsertRows();
            Assert.AreEqual(7, rows.Count);
            Assert.AreEqual("", rows[1].Name, "two new rows above the selection's first row");
            Assert.AreEqual("", rows[2].Name);
            Assert.AreEqual("Item 2", rows[3].Name);

            Select(grid, (0, 0), (3, 1));
            grid.DeleteRows();
            CollectionAssert.AreEqual(new[] { "", "", "Item 3", "", "" }, rows.Select(r => r.Name).ToArray());

            CollectionAssert.AreEqual(new[]
            {
                "preview add 3 2", "added 3 2",
                "preview add 1 2", "added 1 2",
                "preview delete 0,3", "deleted 0,3",
            }, events);
            window.Close();
        });
    }

    [TestMethod]
    public void PreviewAddRows_CanCancel_AndRowsAreAddedToADataTable()
    {
        HeadlessSession.Run(() =>
        {
            var table = new DataTable();
            table.Columns.Add("X", typeof(double));
            table.Columns.Add("Y", typeof(double));
            table.Rows.Add(1.0, 2.0);
            table.Rows.Add(3.0, 4.0);
            var grid = new CopyPasteDataGrid { ItemsSource = table.DefaultView };
