    [TestMethod]
    public void Editing_CommitsWithEnter_AndCancelsWithEscape()
    {
        HeadlessSession.Run(() =>
        {
            var rows = Rows(3);
            var (window, grid) = ShowGrid(rows);
            grid.CurrentCell = new DataGridCellInfo(rows[0], grid.Columns[0], 0, 0);
            Settle();

            window.KeyPressQwerty(PhysicalKey.F2, RawInputModifiers.None);
            Settle();
            var editor = (TextBox)Cell(grid, 0, 0).Content!;
            editor.SelectAll();
            window.KeyTextInput("Renamed");
            window.KeyPressQwerty(PhysicalKey.Enter, RawInputModifiers.None);
            Settle();
            Assert.AreEqual("Renamed", rows[0].Name);
            Assert.AreEqual(1, grid.SelectedCells.Single().RowIndex, "Enter moves down, as in WPF");

            window.KeyPressQwerty(PhysicalKey.F2, RawInputModifiers.None);
            Settle();
            editor = (TextBox)Cell(grid, 1, 0).Content!;
            editor.SelectAll();
            window.KeyTextInput("Discarded");
            window.KeyPressQwerty(PhysicalKey.Escape, RawInputModifiers.None);
            Settle();
            Assert.AreEqual("Item 2", rows[1].Name);
            window.Close();
        });
    }

    [TestMethod]
    public void Keyboard_MovesTheCellSelection_AsInWpf()
    {
        HeadlessSession.Run(() =>
        {
            var rows = Rows(3);
            var (window, grid) = ShowGrid(rows);
            Select(grid, (0, 0));
            grid.CurrentCell = grid.SelectedCells[0];
            Settle();
            string Press(PhysicalKey key, RawInputModifiers modifiers = RawInputModifiers.None)
            {
                window.KeyPressQwerty(key, modifiers);
                Settle();
                return string.Join(" ", grid.SelectedCells.OrderBy(c => c.RowIndex).ThenBy(c => c.Column.DisplayIndex).Select(c => $"{c.RowIndex},{c.Column.DisplayIndex}"));
            }

            Assert.AreEqual("1,0", Press(PhysicalKey.ArrowDown), "an arrow selects the cell it moves to");
            Assert.AreEqual("1,0 1,1", Press(PhysicalKey.ArrowRight, RawInputModifiers.Shift), "Shift extends from the anchor");
            Assert.AreEqual("1,0 1,1 2,0 2,1", Press(PhysicalKey.ArrowDown, RawInputModifiers.Shift));
            Assert.AreEqual("2,0", Press(PhysicalKey.ArrowLeft));
            Assert.AreEqual("0,0", Press(PhysicalKey.ArrowUp, RawInputModifiers.Control), "Ctrl moves to the edge, and selects");
            Assert.AreEqual("0,1", Press(PhysicalKey.Tab), "Tab moves to the next cell");
            Assert.AreEqual("0,2", Press(PhysicalKey.Tab));
            Assert.AreEqual("1,0", Press(PhysicalKey.Tab), "from the last column, to the next row");
            Assert.AreEqual("0,2", Press(PhysicalKey.Tab, RawInputModifiers.Shift), "Shift+Tab goes back");
            Assert.AreEqual("0,2 1,2 2,2", Press(PhysicalKey.End, RawInputModifiers.Control | RawInputModifiers.Shift));
            Assert.AreEqual("1,2", Press(PhysicalKey.Enter, RawInputModifiers.Shift), "Shift+Enter moves up, and selects one cell");

            window.KeyPressQwerty(PhysicalKey.F2, RawInputModifiers.None);
            Settle();
            ((TextBox)Cell(grid, 1, 2).Content!).SelectAll();
            window.KeyTextInput("7");
            Assert.AreEqual("0,2", Press(PhysicalKey.Enter, RawInputModifiers.Shift), "Shift+Enter commits an edit, then moves up");
            Assert.AreEqual(7, rows[1].Count);
            window.Close();
        });
    }

