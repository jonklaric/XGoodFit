    [TestMethod]
    public void Paste_FromOneCell_FillsBeyondIt_AndAddsRows()
    {
        HeadlessSession.Run(() =>
        {
            CultureInfo culture = CultureInfo.CurrentCulture;
            CultureInfo.CurrentCulture = CultureInfo.GetCultureInfo("en-US");
            var rows = Rows(3);
            var (window, grid) = ShowGrid(rows);
            int pasted = 0;
            grid.DataPasted += () => pasted++;
            var added = new List<(int Start, int Count)>();
            grid.RowsAdded += (start, count) => added.Add((start, count));

            Select(grid, (2, 0));
            Clipboard.SetText("A\t1.5\t7\r\nB\t-inf\t8\r\nC\t\t9\r\n");
            grid.PasteClipboard();

            Assert.AreEqual(5, rows.Count, "two rows added for the clipboard's last two lines");
            CollectionAssert.AreEqual(new[] { (3, 2) }, added);
            Assert.AreEqual("A", rows[2].Name);
            Assert.AreEqual(1.5, rows[2].Value);
            Assert.AreEqual(7, rows[2].Count);
            Assert.AreEqual(double.NegativeInfinity, rows[3].Value);
            Assert.IsTrue(double.IsNaN(rows[4].Value), "a blank number is NaN");
            Assert.AreEqual(9, rows[4].Count);
            Assert.AreEqual(1, pasted);
            Assert.AreEqual("A", ((TextBlock)Cell(grid, 2, 0).Content!).Text, "the grid shows the pasted values");
            window.Close();
            CultureInfo.CurrentCulture = culture;
        });
    }

    [TestMethod]
    public void Paste_ParsesNumbers_InTheUsersCultureThenTheInvariantOne()
    {
        HeadlessSession.Run(() =>
        {
            CultureInfo culture = CultureInfo.CurrentCulture;
            try
            {
                var rows = Rows(2);
                var (window, grid) = ShowGrid(rows);

                CultureInfo.CurrentCulture = CultureInfo.GetCultureInfo("de-DE");
                Select(grid, (0, 1));
                Clipboard.SetText("1,5\t1.234\nabc\t4,0");
                grid.PasteClipboard();
                Assert.AreEqual(1.5, rows[0].Value, "German decimal comma");
                Assert.AreEqual(1234, rows[0].Count, "German thousands separator, then converted to int");
                Assert.IsTrue(double.IsNaN(rows[1].Value), "not a number: NaN");
                Assert.AreEqual(4, rows[1].Count);

                CultureInfo.CurrentCulture = CultureInfo.GetCultureInfo("en-US");
                Clipboard.SetText("1,234.5\tabc\n+Infinity");
                Select(grid, (0, 1));
                grid.PasteClipboard();
                Assert.AreEqual(1234.5, rows[0].Value);
                Assert.AreEqual(1234, rows[0].Count, "an int column keeps its value when the text isn't a number");
                Assert.AreEqual(double.PositiveInfinity, rows[1].Value);
                window.Close();
            }
            finally
            {
                CultureInfo.CurrentCulture = culture;
            }
        });
    }

    [TestMethod]
    public void AGeneratedColumnsStringFormat_SetWhileGenerating_IsShown_AndEditsConvertBack()
    {
        HeadlessSession.Run(() =>
        {
            // As RMC-BestFit's input data grids format their generated columns (a date's "g", an index's "F0"),
            // without a converter of their own: ProDataGrid's generated converter made text that ignored the format.
            var rows = Rows(3);
            var (window, grid) = ShowGrid(rows, g => g.AutoGeneratingColumn += (_, e) =>
            {
                if (e.PropertyName != nameof(GridRow.Name))
                    ((ReflectionBinding)((DataGridTextColumn)e.Column).Binding!).StringFormat = "F2";
            });
            Assert.AreEqual("10.50", ((TextBlock)Cell(grid, 0, 1).Content!).Text);
            Assert.AreEqual("1.00", ((TextBlock)Cell(grid, 0, 2).Content!).Text);

            grid.CurrentColumn = grid.Columns[1];
            grid.SelectedItem = rows[0];
            Assert.IsTrue(grid.BeginEdit());
            Settle();
            ((TextBox)Cell(grid, 0, 1).Content!).Text = "3.25";
            Assert.IsTrue(grid.CommitEdit());
            Settle();
            Assert.AreEqual(3.25, rows[0].Value, "the edited text converts back to the number, as without a converter");
            Assert.AreEqual("3.25", ((TextBlock)Cell(grid, 0, 1).Content!).Text);
            CollectionAssert.AreEqual(new[] { 21.0, 31.5 }, rows.Skip(1).Select(r => r.Value).ToArray(), "showing writes nothing back");
            window.Close();
        });
    }

