    [TestMethod]
    public void EditingACell_ReplacesTheOrdinate_WithTheEditedDistribution()
    {
        HeadlessSession.Run(() =>
        {
            using var culture = new CultureScope("en-US");
            var (window, _, grid, data) = ShowEditor();
            var changes = Record(data);

            EditCell(window, grid, 1, 1, "25");

            Assert.AreEqual(25, ((Normal)data[1].Y!).Mean);
            Assert.AreEqual(2, data[1].X);
            CollectionAssert.AreEqual(new[] { NotifyCollectionChangedAction.Replace }, changes);

            EditCell(window, grid, 1, 0, "3");
            Assert.AreEqual(3, data[1].X);
            window.Close();
        });
    }

    [TestMethod]
    public void Validation_FlagsXOutOfOrder_AndMeansOutOfOrder()
    {
        HeadlessSession.Run(() =>
        {
            // Ascending X; the demo's descending Y.
            var (window, _, grid, _) = ShowEditor(e => e.OrderY = SortOrder.Descending, (0, 30), (4, 24), (2, 19));

            // As upstream's PropertyRule: the order rule follows X's default rule, so its message starts with a new line.
            DataGridCell x = Cell(grid, 2, 0);
            Assert.AreEqual(grid.ErrorCellBackgroundBrush, x.Background);
            Assert.AreEqual(Environment.NewLine + "X values must be in Ascending order.", ToolTip.GetTip(x));
            Assert.AreNotEqual(grid.ErrorCellBackgroundBrush, Cell(grid, 2, 1).Background, "the means descend");
            window.Close();
        });
        HeadlessSession.Run(() =>
        {
            var (window, _, grid, _) = ShowEditor(e => e.OrderY = SortOrder.Descending, (0, 30), (2, 31), (4, 19));
            DataGridCell mean = Cell(grid, 1, 1);
            Assert.AreEqual(grid.ErrorCellBackgroundBrush, mean.Background);
            StringAssert.Contains((string)ToolTip.GetTip(mean)!, "Mean values must be in Descending order.");
            window.Close();
        });
    }

    [TestMethod]
    public void AddingInsertingAndDeletingRows_EditTheData()
    {
        HeadlessSession.Run(() =>
        {
            var (window, editor, grid, data) = ShowEditor();

            grid.AddRows(1);
            Assert.AreEqual(4, data.Count);
            Assert.AreEqual(0, data[3].X, "a new row's X is 0");
            Assert.AreEqual(30, ((Normal)data[3].Y!).Mean, "and its distribution the first row's");
            Assert.AreEqual(4, grid.Items.Count);

            Select(grid, (1, 0));
            grid.InsertRows();
            Assert.AreEqual(5, data.Count);
            Assert.AreEqual(0, data[1].X);
            Assert.AreEqual(2, data[2].X);

            Select(grid, (1, 0), (3, 1));
            grid.DeleteRows();
            CollectionAssert.AreEqual(new[] { 0.0, 2, 0 }, data.Select(o => o.X).ToArray());
            Assert.AreEqual(3, grid.Items.Count);
            Assert.AreEqual(3, editor.DistributionRows.Count);
            window.Close();
        });
    }

    [TestMethod]
    public void Paste_WritesTheData_ThenValidatesAndResetsIt()
    {
        HeadlessSession.Run(() =>
        {
            using var culture = new CultureScope("en-US");
            var (window, _, grid, data) = ShowEditor();
            var changes = Record(data);

            Select(grid, (1, 0));
            Clipboard.SetText("10\t50\t2\r\n20\t40\t3\r\n30\t35\t4\r\n");
            grid.PasteClipboard();

            CollectionAssert.AreEqual(new[] { 0.0, 10, 20, 30 }, data.Select(o => o.X).ToArray(), "a row is added for the last line");
            CollectionAssert.AreEqual(new[] { 30.0, 50, 40, 35 }, data.Select(o => ((Normal)o.Y!).Mean).ToArray());
            Assert.AreEqual(4.0, ((Normal)data[3].Y!).StandardDeviation);
            Assert.AreEqual(NotifyCollectionChangedAction.Reset, changes.Last());
            Assert.IsFalse(data.SuppressCollectionChanged);
            Assert.IsNull(WpfCompat.Input.Mouse.OverrideCursor);
            Settle();
            Assert.AreEqual("50", CellText(grid, 1, 1));
            window.Close();
        });
    }

    [TestMethod]
    public void ChangesToTheData_ShowInTheGrid_AsTheDemosTestButtonMakesThem()
    {
        HeadlessSession.Run(() =>
        {
            var (window, _, grid, data) = ShowEditor();

            // The demo's "Test Data Modification" button.
            data[0] = new UncertainOrdinate(data[0].X + 1d, data[0].Y!.Clone());
            data.Add(new UncertainOrdinate(0d, data[0].Y!.Clone()));
            Settle();

            Assert.AreEqual(4, grid.Items.Count);
            Assert.AreEqual("1", CellText(grid, 0, 0));
            Assert.AreEqual("0", CellText(grid, 3, 0));

            data.RemoveAt(1);
            Settle();
            Assert.AreEqual(3, grid.Items.Count);
            Assert.AreEqual("4", CellText(grid, 1, 0));
            window.Close();
        });
    }

    [TestMethod]
    public void ClickingBelowTheRows_EndsTheEdit_AndClearsTheSelection()
    {
        HeadlessSession.Run(() =>
        {
            var (window, _, grid, _) = ShowEditor();
            Select(grid, (0, 1), (1, 1));
            Assert.AreEqual(2, grid.SelectedCells.Count);

            var rows = grid.GetVisualDescendants().OfType<DataGridRowsPresenter>().Single();
            // Below the rows, in the grid's empty space.
            window.ClickAt(rows, new Point(rows.Bounds.Width / 2, rows.Bounds.Height - 5));
            Assert.AreEqual(0, grid.SelectedCells.Count);
            window.Close();
        });
    }

    // The editor showing a Normal distribution at each X (the demo's depths and velocities by default).
    private static (Window Window, UncertainOrderedTableEditor Editor, ValidationDataGrid Grid, UncertainOrderedPairedData Data) ShowEditor(
        Action<UncertainOrderedTableEditor>? configure = null, params (double X, double Mean)[] values)
    {
        UseAppResources();
        if (values.Length == 0)
            values = [(0, 30), (2, 24), (4, 19)];
        var data = new UncertainOrderedPairedData(values.Select(v => new UncertainOrdinate(v.X, new Normal(v.Mean, 1))).ToList(),
            false, SortOrder.Ascending, false, SortOrder.Descending, UnivariateDistributionType.Normal);
        var editor = new UncertainOrderedTableEditor();
        configure?.Invoke(editor);
        editor.UncertainOrderedData = data;
        var window = Show(editor, 600, 400);
        var grid = editor.GetVisualDescendants().OfType<ValidationDataGrid>().Single();
        grid.Focus();
        Settle();
        return (window, editor, grid, data);
    }

    // Edits a cell as a user does: F2, the text, Enter.
    private static void EditCell(Window window, CopyPasteDataGrid grid, int row, int column, string text)
    {
        grid.Focus();
        grid.CurrentCell = new DataGridCellInfo(grid.Items[row], grid.Columns[column], row, column);
        Settle();
        window.KeyPressQwerty(PhysicalKey.F2, RawInputModifiers.None);
        Settle();
        var box = (TextBox)Cell(grid, row, column).Content!;
        box.SelectAll();
        window.Type(text);
        window.KeyPressQwerty(PhysicalKey.Enter, RawInputModifiers.None);
        Settle();
    }

    // The collection changes the data raises.
    private static List<NotifyCollectionChangedAction> Record(UncertainOrderedPairedData data)
    {
        var changes = new List<NotifyCollectionChangedAction>();
        data.CollectionChanged += (_, e) => changes.Add(e.Action);
        return changes;
    }
