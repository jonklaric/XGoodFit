    [TestMethod]
    public void Columns_AreGenerated_WithWrappedHeaders_UnderTheMergedHeader()
    {
        HeadlessSession.Run(() =>
        {
            var (window, editor, grid, _) = ShowEditor(e => { e.XColumnHeader = "Depth"; e.YColumnHeader = "Velocity"; });

            CollectionAssert.AreEqual(new object[] { "X", "Mean (µ)", "Std Dev (σ)" }, grid.Columns.Select(c => c.Header).ToArray());
            var wrapped = (ControlTheme)editor.Resources["WrappedColumnHeaderStyle"]!;
            Assert.IsTrue(grid.Columns.All(c => c.HeaderTheme == wrapped));
            Assert.AreSame(wrapped, editor.ColumnHeaderStyle, "the editor's default header style");
            Assert.AreEqual("30", CellText(grid, 0, 1));
            Assert.AreEqual("1", CellText(grid, 0, 2));

            // The merged header: one column for the row headers, then one per grid column.
            var merged = editor.FindControl<Grid>("MergedColumnHeaderGrid")!;
            Assert.AreEqual(Visibility.Visible, merged.Visibility);
            Assert.AreEqual(4, merged.ColumnDefinitions.Count);
            for (int i = 0; i < grid.Columns.Count; i++)
            {
                Assert.AreEqual(grid.Columns[i].ActualWidth, merged.ColumnDefinitions[i + 1].Width.Value, 0.01, "the merged header's columns follow the grid's");
            }
            var x = editor.FindControl<DataGridColumnHeader>("XGridColumnHeader")!;
            var y = editor.FindControl<DataGridColumnHeader>("YGridColumnHeader")!;
            Assert.AreEqual("Depth", x.Content);
            Assert.AreEqual("Velocity", y.Content);
            Assert.AreSame(wrapped, x.Theme);
            Assert.AreEqual(grid.Columns[0].ActualWidth, x.Bounds.Width, 1);
            Assert.AreEqual(grid.Columns[1].ActualWidth + grid.Columns[2].ActualWidth, y.Bounds.Width, 1, "the Y header spans the parameters");

            // A wider grid widens the merged header's columns too.
            window.Width = 800;
            Settle();
            Assert.AreEqual(grid.Columns[1].ActualWidth, merged.ColumnDefinitions[2].Width.Value, 0.01);
            window.Close();
        });
    }

    [TestMethod]
    public void Cells_HaveWpfsOwnCellStyle_AsTheGridsCellStyleIsBoundToNull()
    {
        HeadlessSession.Run(() =>
        {
            // Upstream binds the grid's CellStyle to the editor's, which is null unless set: the cells take WPF's own
            // cell style under the grid's error trigger.
            var (window, editor, grid, _) = ShowEditor();
            Assert.IsNull(grid.CellTheme);
            Assert.AreSame(editor.FindResource("DataGridCellDefaultTheme"), grid.Columns[1].CellTheme!.BasedOn);
            Assert.IsNotNull(Cell(grid, 0, 1).GetVisualDescendants().OfType<Border>().FirstOrDefault(b => b.Name == "Bd"), "Aero2's cell template");

            var custom = new ControlTheme(typeof(DataGridCell)) { BasedOn = (ControlTheme)editor.FindResource("Right_CellStyle")! };
            window.Close();
            (window, editor, grid, _) = ShowEditor(e => e.CellStyle = custom);
            Assert.AreSame(custom, grid.CellTheme);
            Assert.AreSame(custom, grid.Columns[1].CellTheme!.BasedOn);
            window.Close();
        });
    }

    [TestMethod]
    public void BestFitsSettings_CentreTheHeaders_AndHideTheMergedHeader()
    {
        HeadlessSession.Run(() =>
        {
            ObservableCollection<DataGridColumn>? generated = null;
            var (window, editor, grid, _) = ShowEditor(e =>
            {
                // As BivariateAnalysisPropertiesControl.xaml.
                e.ColumnHeaderStyle = (ControlTheme)Application.Current!.FindResource("Center_ColumnHeaderStyle")!;
                e.IsMergedHeaderVisible = false;
                e.XColumnHeader = "X";
                e.YColumnHeader = "Y";
                e.ColumnsAutoGenerated += (sender, columns) =>
                {
                    generated = columns;
                    foreach (var column in columns)
                    {
                        if (column is DataGridTextColumn { Binding: ReflectionBinding { Path: "P1" } } text)
                            text.Header = "Y";
                    }
                };
            });

            Assert.AreSame(grid.Columns, generated, "the event gives the grid's columns");
            CollectionAssert.AreEqual(new object[] { "X", "Y", "Std Dev (σ)" }, grid.Columns.Select(c => c.Header).ToArray());
            Assert.IsTrue(grid.Columns.All(c => c.HeaderTheme == editor.ColumnHeaderStyle));
            Assert.AreEqual(Visibility.Collapsed, editor.FindControl<Grid>("MergedColumnHeaderGrid")!.Visibility);

            // Only the wrapped header style's headers select their column when clicked.
            DataGridColumnHeader header = grid.GetVisualDescendants().OfType<DataGridColumnHeader>().Single(h => h.OwningColumn == grid.Columns[0]);
            window.ClickAt(header);
            Assert.AreEqual(0, grid.SelectedCells.Count);
            window.Close();
        });
    }

